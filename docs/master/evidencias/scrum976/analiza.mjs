import fs from 'node:fs';
const r = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const tot = r.length;
const verdes = r.filter((x) => x.code === 0 && x.tests > 0 && x.pass === x.tests - (x.skipped || 0) - (x.todo || 0) && !x.skipped);
const conSkip = r.filter((x) => x.code === 0 && x.skipped);
const rojos = r.filter((x) => x.code !== 0);
const sinTests = r.filter((x) => x.code === 0 && !(x.tests > 0));
console.log({ tot, verdes: verdes.length, conSkip: conSkip.length, rojos: rojos.length, sinTests: sinTests.length });
const lim = (x) => !x.dist && !x.base && !x.nav;
const cand = verdes.filter(lim);
console.log('verdes sin dist/base/nav estatico:', cand.length, 'suma s:', (cand.reduce((a, x) => a + x.ms, 0) / 1000).toFixed(1));
console.log('  de ellos sin proc:', cand.filter((x) => !x.proc).length);
console.log('rojos (sin dist/DB) por causa: dist', rojos.filter((x) => x.dist).length, 'base', rojos.filter((x) => x.base).length, 'nav', rojos.filter((x) => x.nav).length, 'ninguna', rojos.filter(lim).length);
console.log('ROJOS que no declaran dist/base/nav (investigar):');
for (const x of rojos.filter(lim)) console.log('  ', x.f, x.ms, x.tests, x.fail);
console.log('CON SKIP, sin dist/base/nav:');
for (const x of conSkip.filter(lim)) console.log('  ', x.f, x.ms, x.tests, 'skip', x.skipped);
console.log('los citados:');
for (const n of [237, 258, 267, 514, 522, 548, 723]) for (const x of r.filter((y) => y.f.startsWith('scrum' + n + '-'))) console.log('  ', x.f, x.code, x.ms + 'ms', 't' + x.tests, 'dist', x.dist, 'base', x.base, 'nav', x.nav, 'proc', x.proc);
const lentos = cand.sort((a, b) => b.ms - a.ms).slice(0, 12);
console.log('candidatos mas lentos:'); for (const x of lentos) console.log('  ', x.f, x.ms);
fs.writeFileSync(process.argv[3], JSON.stringify(cand.map((x) => x.f)));
